-- ============================================================
-- FORNECEDORES E COMPRAS
--
-- • fornecedores  → quem vende pra loja (nome, telefone, contato)
-- • compras       → cada compra: fornecedor, data, total, paga ou a pagar
-- • compra_itens  → o que veio na compra (produto, quantidade, custo)
--
-- O menu "Compras" só aparece nas lojas que têm essas tabelas.
-- Rode só nos schemas da lista abaixo. Pra ativar numa loja, coloque o
-- schema dela na lista e rode de novo (não mexe no que já existe).
-- O schema public precisa estar na lista: o nova-adega.sql copia dele.
-- ============================================================

do $$
declare
  lojas text[] := array['public', 'demogas', 'demotabacaria'];   -- <<< SCHEMAS COM COMPRAS
  s text;
  tipo_id text;
  t text;
begin
  foreach s in array lojas loop
    continue when to_regclass(format('%I.produtos', s)) is null;

    -- mesmo tipo do id de produtos (uuid ou número)
    select format_type(a.atttypid, a.atttypmod) into tipo_id
    from pg_attribute a where a.attrelid = format('%I.produtos', s)::regclass and a.attname = 'id';

    execute format($t$
      create table if not exists %I.fornecedores (
        id uuid primary key default gen_random_uuid(),
        nome text not null,
        telefone text,
        contato text,
        observacao text,
        ativo boolean not null default true,
        created_at timestamptz not null default now()
      )$t$, s);

    execute format($t$
      create table if not exists %I.compras (
        id uuid primary key default gen_random_uuid(),
        numero bigint generated by default as identity,
        fornecedor_id uuid references %I.fornecedores(id) on delete set null,
        fornecedor_nome text,
        data date not null default current_date,
        total numeric(12,2) not null default 0,
        status text not null default 'paga',          -- paga | a_pagar
        forma_pagamento text,
        vencimento date,
        pago_em timestamptz,
        observacao text,
        created_at timestamptz not null default now()
      )$t$, s, s);

    execute format($t$
      create table if not exists %I.compra_itens (
        id uuid primary key default gen_random_uuid(),
        compra_id uuid not null references %I.compras(id) on delete cascade,
        produto_id %s references %I.produtos(id) on delete set null,
        nome_produto text not null,
        quantidade numeric(12,3) not null check (quantidade > 0),
        custo_unitario numeric(12,4) not null default 0,
        subtotal numeric(12,2) not null default 0
      )$t$, s, s, tipo_id, s);

    execute format('create index if not exists compras_data_idx on %I.compras (data desc)', s);
    execute format('create index if not exists compra_itens_compra_idx on %I.compra_itens (compra_id)', s);

    foreach t in array array['fornecedores','compras','compra_itens'] loop
      execute format('grant all on %I.%I to anon, authenticated, service_role', s, t);
      execute format('alter table %I.%I enable row level security', s, t);
      begin execute format('create policy acesso_app on %I.%I for all using (true) with check (true)', s, t);
      exception when duplicate_object then null; end;
    end loop;
  end loop;
end $$;

notify pgrst, 'reload schema';

-- Conferência: cada loja da lista deve aparecer com 3
select table_schema, count(*) as tabelas
from information_schema.tables
where table_name in ('fornecedores', 'compras', 'compra_itens')
group by table_schema order by table_schema;
