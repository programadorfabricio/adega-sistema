-- ============================================================
-- DELIVERY: bairros (taxa de entrega) e pedidos de entrega
-- Cria as tabelas no schema public (demonstração) e em todas as
-- adegas que já existem. Pode rodar de novo sem erro.
-- Adegas novas recebem as tabelas pelo nova-adega.sql.
-- ============================================================

do $$
declare
  s text;
begin
  for s in
    select nspname from pg_namespace n
    where nspname = 'public'
       or exists (select 1 from pg_class c where c.relnamespace = n.oid and c.relname = 'produtos' and c.relkind = 'r')
  loop
    execute format($t$
      create table if not exists %I.bairros (
        id uuid primary key default gen_random_uuid(),
        nome text not null,
        taxa numeric(10,2) not null default 0,
        created_at timestamptz not null default now()
      )$t$, s);

    execute format($t$
      create table if not exists %I.entregas (
        id uuid primary key default gen_random_uuid(),
        numero bigint generated by default as identity,
        cliente_nome text not null,
        telefone text,
        endereco text,
        bairro text,
        referencia text,
        itens jsonb not null default '[]'::jsonb,
        subtotal numeric(10,2) not null default 0,
        taxa numeric(10,2) not null default 0,
        total numeric(10,2) not null default 0,
        forma_pagamento text not null default 'dinheiro',
        troco_para numeric(10,2),
        observacao text,
        status text not null default 'preparando',
        venda_id uuid,
        created_at timestamptz not null default now(),
        saiu_em timestamptz,
        entregue_em timestamptz
      )$t$, s);

    execute format('create index if not exists entregas_status_idx on %I.entregas (status, created_at desc)', s);
    execute format('create index if not exists entregas_telefone_idx on %I.entregas (telefone, created_at desc)', s);

    execute format('grant all on %I.bairros, %I.entregas to anon, authenticated, service_role', s, s);
    execute format('alter table %I.bairros enable row level security', s);
    execute format('alter table %I.entregas enable row level security', s);
    begin execute format('create policy acesso_app on %I.bairros for all using (true) with check (true)', s);
    exception when duplicate_object then null; end;
    begin execute format('create policy acesso_app on %I.entregas for all using (true) with check (true)', s);
    exception when duplicate_object then null; end;

    begin execute format('alter publication supabase_realtime add table %I.entregas', s);
    exception when duplicate_object then null; end;
    begin execute format('alter publication supabase_realtime add table %I.bairros', s);
    exception when duplicate_object then null; end;
  end loop;
end $$;

-- Conferência: deve listar public e cada adega
select table_schema, table_name from information_schema.tables
where table_name in ('bairros', 'entregas') order by 1, 2;
